import assert from 'node:assert/strict';
import { onRequestGet, onRequestPost } from '../functions/api/list.js';
import { onRequestPost as authPost } from '../functions/api/auth.js';
const mem = new Map();
const kv={get:async key=>mem.has(key)?mem.get(key):null,put:async (key,val)=>{mem.set(key,val)},delete:async key=>{mem.delete(key)}};
const env={LIST:kv,ANKOO_LIST_CODE:'MyOldCode-123',ANKOO_ADMIN_PASSWORD:'4826',ANKOO_SESSION_SECRET:'SESSION_SECRET_long_random_never_shared_1234567890'};
const get=async customEnv=>{const resp=await onRequestGet({env:customEnv??env});return {status:resp.status,body:await resp.json()}};
const req=(route,body,cookie='',origin='https://ankoo.pages.dev')=>new Request(`https://ankoo.pages.dev/api/${route}`,{method:'POST',headers:{'content-type':'application/json',origin,...(cookie?{cookie}:{})},body:JSON.stringify(body)});
const auth=await authPost({request:req('auth',{action:'login',password:env.ANKOO_ADMIN_PASSWORD}),env});
assert.equal(auth.status,200);const cookie=auth.headers.get('set-cookie').split(';')[0];
const post=async (body,custom={})=>{
 const request=req('list',body,custom.cookie===undefined?cookie:custom.cookie,custom.origin||'https://ankoo.pages.dev');
 const resp=await onRequestPost({request,env:custom.env||env});return {status:resp.status,body:await resp.json()};
};
assert.equal((await post({action:'add',items:[{id:'333'}]},{cookie:''})).status,401,'Guests must not edit');
assert.equal((await get()).status,409,'Never implicitly create a fresh empty KV under wrong legacy code');
assert.equal((await post({action:'add',items:[{id:'456'}]})).status,409);
assert.equal((await get({LIST:kv})).status,503);
mem.set('l:MyOldCode-123',JSON.stringify([{id:'111',name:'OLD',img:'https://rbxcdn.com/111',body:''},{id:'222',name:'TWO',img:'',body:''}]));
assert.deepEqual((await get()).body.list.map(x=>x.id),['111','222']);
let resp=await post({action:'add',items:[{id:'333',name:'NEW',img:'',body:''},{id:'222',name:'DUPLICATED'}]});
assert.equal(resp.status,200);assert.equal(resp.body.added,1);assert.equal(resp.body.exists,1);
assert.deepEqual(resp.body.list.map(x=>x.id),['333','111','222']);
resp=await post({action:'add',items:[{id:'444',name:'Newest'}]});
assert.deepEqual(resp.body.list.map(x=>x.id),['444','333','111','222']);
resp=await post({action:'move',id:'333',toIndex:3});
assert.deepEqual(resp.body.list.map(x=>x.id),['444','111','222','333']);
resp=await post({action:'update',items:[{id:'444',name:'Updated',body:'https://rbxcdn.com/444'},{id:'999',name:'Should not be inserted'}]});
assert.equal(resp.body.list.find(x=>x.id==='444').name,'Updated');
assert.equal(resp.body.list.some(x=>x.id==='999'),false);
resp=await post({action:'remove',id:'111'});
assert.deepEqual(resp.body.list.map(x=>x.id),['444','222','333']);
assert.equal((await post({action:'add',items:[{id:'bad'}]})).status,400);
assert.equal((await post({action:'move',id:'333',toIndex:'0'})).status,400);
assert.equal((await post({action:'add',items:[{id:'55'}]},{origin:'https://example.net'})).status,403);
assert.equal((await post({action:'add',items:[{id:'555'}]},{cookie:'ankoo_admin_session=forged'})).status,401);
assert.deepEqual((await get()).body.list.map(x=>x.id),['444','222','333']);
console.log('API KV: autorização obrigatória, dados antigos preservados, deduplicação, topo, mover, atualizar e remover OK.');